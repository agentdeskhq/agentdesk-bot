async def handle_message(sender_id: str, text: str, cfg: Dict[str, Any]) -> None:
    # Special command: anyone can ask for their PSID (needed to configure OWNER_IDS).
    if normalize(text) == "myid":
        await send_message(sender_id, f"Your PSID for this page: {sender_id}")
        return

    # Owner messages: check for escalation responses first.
    if is_owner(sender_id):
        await handle_owner_message(sender_id, text)
        # If it wasn't an escalation response, continue as owner chat.
        if parse_owner_intent(text):
            return
        history = get_history(sender_id)
        try:
            reply = await generate_reply(text, build_owner_prompt(), history)
        except Exception as e:
            log.warning("owner reply failed: %s", e)
            reply = ""
        if reply:
            add_history(sender_id, "user", text)
            add_history(sender_id, "model", reply)
            await send_message(sender_id, reply)
        else:
            await send_message(sender_id, "বস, এই মুহূর্তে একটু সমস্যা হচ্ছে।")
        return

    # Manual kill-switch: bot stays completely silent when turned off.
    if not BOT_ENABLED:
        log.info("bot disabled, skipping message from %s", sender_id)
        return

    # Human took over: stay silent for this customer.
    if is_paused(sender_id):
        log.info("bot paused for %s, skipping", sender_id)
        return

    # Don't interrupt a pending escalation.
    if sender_id in ESCALATIONS and ESCALATIONS[sender_id]["status"] == "waiting":
        log.info("escalation pending for %s, skipping", sender_id)
        return

    history = get_history(sender_id)

    # Customer asked for a human: start the 2-minute smart escalation.
    if needs_escalation(text):
        ESCALATIONS[sender_id] = {"status": "waiting", "text": text}
        add_history(sender_id, "user", text)
        await notify_owners_escalation(sender_id, text)
        wait_msg = "আপনাকে আমাদের টিমের সাথে যুক্ত করছি, একটু অপেক্ষা করুন..."
        add_history(sender_id, "model", wait_msg)
        await send_message(sender_id, wait_msg)
        asyncio.create_task(escalation_timeout(sender_id))
        log.info("escalation started for %s", sender_id)
        return

    # SUPER SMART pipeline: AI understands everything.
    # 1. Similar-question cache (zero API cost, answers were smart to begin with)
    reply = get_similar_cached(text)
    source = "similar-cache" if reply else None

    # 2. AI providers with automatic failover (smart intent understanding)
    if not reply:
        try:
            reply = await generate_reply(
                text, build_system_prompt(cfg, bool(history)), history
            )
            source = "ai"
        except Exception as e:
            log.warning("all providers failed: %s", e)
            reply = ""
        if reply:
            set_dynamic_cached(text, reply)

    if reply:
        log.info("reply source=%s chars=%d", source, len(reply))
        add_history(sender_id, "user", text)
        add_history(sender_id, "model", reply)
        await send_message(sender_id, reply)
    else:
        # Never leave the customer hanging: polite fallback when AI is unavailable.
        await send_message(
            sender_id,
            "দুঃখিত, এই মুহূর্তে একটু ব্যস্ত আছি। কিছুক্ষণ পর আবার মেসেজ করুন।",
        )


def verify_signature(body, signature=None):
    if not APP_SECRET:
        return True
    if not signature or not signature.startswith("sha256="):
        return False
    expected = hmac.new(APP_SECRET.encode(), body, hashlib.sha256).hexdigest()
    return hmac.compare_digest("sha256=" + expected, signature)


