def match_faq(text: str) -> Optional[str]:
    """Keyword-intent match. Returns pre-written answer or None."""
    words = normalize(text).split()
    best_answer, best_score = None, 0
    for entry in FAQ:
        # longer keywords = more specific; weight by length
        score = sum(len(kw) for kw in entry["keywords"] if word_match(kw, words))
        if score > best_score:
            best_score, best_answer = score, entry["answer"]
    return best_answer if best_score > 0 else None


# --- Dynamic similar-question cache (zero API cost on rephrased repeats) ---
DYNAMIC_CACHE: Dict[str, str] = {}  # normalized question -> answer
MAX_CACHE = 200
SIMILARITY_THRESHOLD = 0.6


def get_similar_cached(text: str) -> Optional[str]:
    norm = normalize(text)
    best_answer, best_score = None, 0.0
    for q, a in DYNAMIC_CACHE.items():
        s = similarity(norm, q)
        if s > best_score:
            best_score, best_answer = s, a
    return best_answer if best_score >= SIMILARITY_THRESHOLD else None


def set_dynamic_cached(text: str, reply: str) -> None:
    if len(DYNAMIC_CACHE) >= MAX_CACHE:
        DYNAMIC_CACHE.pop(next(iter(DYNAMIC_CACHE)))
    DYNAMIC_CACHE[normalize(text)] = reply


# --- Human takeover: pause bot when a human (page admin) replies ---
PAUSED_UNTIL: Dict[str, float] = {}
LAST_BOT_SEND: Dict[str, float] = {}  # recipient -> timestamp of our last API send
ECHO_GRACE_SECONDS = 15  # echoes within this window after our send are our own


def pause_bot(recipient_id: str) -> None:
    PAUSED_UNTIL[recipient_id] = time.time() + PAUSE_SECONDS
    log.info("bot paused for %s (%ds)", recipient_id, PAUSE_SECONDS)


def is_paused(sender_id: str) -> bool:
    return PAUSED_UNTIL.get(sender_id, 0) > time.time()


def is_own_echo(recipient_id: str) -> bool:
    """True if this echo is likely our own just-sent bot message."""
    return time.time() - LAST_BOT_SEND.get(recipient_id, 0) < ECHO_GRACE_SECONDS


# --- Escalation: customer asks for a human ---
ESCALATION_KEYWORDS = [
    "মানুষ", "human", "অ্যাডমিন", "admin", "কর্মচারী", "staff",
    "কেউ আছেন", "live agent", "real person", "আসল মানুষ",
    "ফোন", "phone", "কল", "call",
]


def needs_escalation(text: str) -> bool:
    words = normalize(text).split()
    norm = normalize(text)
    for kw in ESCALATION_KEYWORDS:
        # multi-word phrases: substring check on normalized text
        if " " in kw:
            if kw in norm:
                return True
        elif word_match(kw, words):
            return True
    return False


async def notify_admin(customer_id: str, customer_text: str) -> None:
    """Alert the page owner that a customer needs human help."""
    if not ADMIN_MESSENGER_ID:
        log.info("escalation requested but ADMIN_MESSENGER_ID not set")
        return
    url = f"https://graph.facebook.com/{GRAPH_VERSION}/me/messages"
    msg = (
        "🔔 Customer needs human help.\n"
        f"Customer ID: {customer_id}\n"
        f"Message: {customer_text[:300]}"
    )
    async with httpx.AsyncClient(timeout=30) as client:
        try:
            await client.post(
                url,
                params={"access_token": PAGE_ACCESS_TOKEN},
                json={"recipient": {"id": ADMIN_MESSENGER_ID}, "message": {"text": msg}},
            )
            log.info("admin notified for customer %s", customer_id)
        except Exception as e:
            log.warning("admin notify failed: %s", e)


