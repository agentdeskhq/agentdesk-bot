def normalize(text):
    t = text.lower().strip()
    for ch in "?!।.,;:\"'()[]{}":
        t = t.replace(ch, "")
    return " ".join(t.split())


def similarity(a, b):
    wa = set(normalize(a).split())
    wb = set(normalize(b).split())
    if not wa or not wb:
        return 0.0
    return len(wa & wb) / len(wa | wb)


def word_match(kw, words):
    for w in words:
        if w == kw:
            return True
        if w.startswith(kw) and len(w) - len(kw) <= 2:
            return True
    return False


