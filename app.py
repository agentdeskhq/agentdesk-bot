"""AgentDesk Messenger webhook service.

Receives Messenger message events for connected Facebook Pages, generates a
reply with AI providers (Gemini primary, Groq and OpenRouter fallback), and
sends it back through the Graph API.

Reply pipeline (cheapest first):
1. Human takeover check (bot stays silent if admin recently replied).
2. Escalation check (customer asked for human -> notify admin).
3. Pre-written FAQ answers (zero API cost).
4. Similar-question cache (zero API cost).
5. Gemini -> Groq -> OpenRouter automatic failover (same prompt + history).

All secrets come from environment variables. See .env.example.
"""

