async def gemini_reply(user_text, system_prompt, history):
    url = (
        "https://generativelanguage.googleapis.com/v1beta/models/"
        f"{GEMINI_MODEL}:generateContent"
    )
    contents: List[Dict[str, Any]] = [
        {"role": turn["role"], "parts": [{"text": turn["text"]}]} for turn in history
    ]
    contents.append({"role": "user", "parts": [{"text": user_text}]})
    payload = {
        "systemInstruction": {"parts": [{"text": system_prompt}]},
        "contents": contents,
        "generationConfig": {"maxOutputTokens": 1000, "temperature": 0.7},
    }
    async with httpx.AsyncClient(timeout=30) as client:
        r = None
        for attempt in range(2):
            r = await client.post(url, params={"key": GEMINI_API_KEY}, json=payload)
            if r.status_code == 429 and attempt == 0:
                log.warning("gemini rate limited (429), retrying once")
                await asyncio.sleep(5)
                continue
            break
        r.raise_for_status()
        data = r.json()
    try:
        cand = data["candidates"][0]
        parts = cand.get("content", {}).get("parts", [])
        text = "".join(p.get("text", "") for p in parts).strip()
        log.info("gemini ok, chars=%d", len(text))
        return text
    except (KeyError, IndexError, TypeError):
        log.warning("gemini: unexpected response shape")
        return ""


async def openai_compat_reply(
    name: str,
    url: str,
    api_key: str,
    model: str,
    user_text: str,
    system_prompt: str,
    history: List[Dict[str, str]],
    extra_headers: Optional[Dict[str, str]] = None,
) -> str:
    """Generic OpenAI-compatible chat provider. Same prompt + history for all."""
    messages: List[Dict[str, str]] = [
        {"role": "system", "content": system_prompt}
    ]
    for turn in history:
        role = "assistant" if turn["role"] == "model" else turn["role"]
        messages.append({"role": role, "content": turn["text"]})
    messages.append({"role": "user", "content": user_text})
    payload = {
        "model": model,
        "messages": messages,
        "max_tokens": 500,
        "temperature": 0.7,
    }
    headers = {"Authorization": f"Bearer {api_key}"}
    if extra_headers:
        headers.update(extra_headers)
    async with httpx.AsyncClient(timeout=30) as client:
        r = await client.post(url, headers=headers, json=payload)
        r.raise_for_status()
        data = r.json()
    try:
        text = data["choices"][0]["message"]["content"].strip()
        log.info("%s ok, chars=%d", name, len(text))
        return text
    except (KeyError, IndexError, TypeError):
        log.warning("%s: unexpected response shape", name)
        return ""


