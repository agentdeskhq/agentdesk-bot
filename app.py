@app.post("/webhook")
async def webhook_receive(
    request: Request,
    background_tasks: BackgroundTasks,
    x_hub_signature_256: Optional[str] = Header(default=None),
):
    body = await request.body()
    if not verify_signature(body, x_hub_signature_256):
        return PlainTextResponse("Invalid signature", status_code=403)

    data = await request.json()
    if data.get("object") != "page":
        return PlainTextResponse("Ignored", status_code=200)

    for entry in data.get("entry", []):
        page_id = str(entry.get("id", ""))
        cfg = CLIENTS.get(page_id, DEFAULT_CLIENT)
        for event in entry.get("messaging", []):
            # Skip delivery confirmations and read receipts.
            if event.get("delivery") or event.get("read"):
                continue
            msg = event.get("message") or {}
            # Our own sent messages (echo): a human admin just replied,
            # so pause the bot for that customer to avoid talking over them.
            # (Echoes arriving right after our own API send are our own message.)
            if msg.get("is_echo"):
                recipient_id = (event.get("recipient") or {}).get("id")
                if recipient_id and not is_own_echo(recipient_id):
                    pause_bot(recipient_id)
                continue
            sender_id = (event.get("sender") or {}).get("id")
            text = (msg.get("text") or "").strip()
            if not sender_id or not text:
                continue
            background_tasks.add_task(handle_message, sender_id, text, cfg)

    return PlainTextResponse("EVENT_RECEIVED", status_code=200)
