async def escalation_timeout(customer_id: str) -> None:
    """After 2 min with no owner reply, politely keep customer with the bot."""
    await asyncio.sleep(ESCALATION_TIMEOUT)
    esc = ESCALATIONS.get(customer_id)
    if esc and esc["status"] == "waiting":
        esc["status"] = "timeout"
        ESCALATIONS.pop(customer_id, None)
        log.info("escalation timeout for %s", customer_id)
        await send_message(
            customer_id,
            "দুঃখিত, এই মুহূর্তে আমাদের টিম ব্যস্ত আছে। চলুন, আমি আপনার সাহায্য করি। কী জানতে চান?",
        )


def parse_owner_intent(text: str) -> Optional[str]:
    """Return 'accept', 'decline', 'release', or None from owner's reply."""
    norm = normalize(text)
    if any(kw in norm for kw in ["দেখছি", "নিচ্ছি", "ঠিক আছে", "ok", "okay", "yes", "yeah", "হ্যাঁ", "আসছি"]):
        return "accept"
    if any(kw in norm for kw in ["ব্যস্ত", "busy", "পারব না", "পারবো না", "না", "no", "not now"]):
        return "decline"
    if any(kw in norm for kw in ["ছেড়ে দাও", "ছেড়ে দাও", "ছাড়ো", "release", "ফিরিয়ে দাও", "শেষ", "done"]):
        return "release"
    return None


async def handle_owner_message(owner_id: str, text: str) -> None:
    """Owner replied: check if it's a response to a pending escalation."""
    intent = parse_owner_intent(text)
    if not intent:
        # Not an escalation response; treat as normal owner chat.
        return
    # Release: owner done with a customer, hand back to bot.
    if intent == "release":
        released = False
        for customer_id, esc in list(ESCALATIONS.items()):
            if esc["status"] == "accepted":
                PAUSED_UNTIL.pop(customer_id, None)
                ESCALATIONS.pop(customer_id, None)
                await send_message(owner_id, f"ঠিক আছে, {customer_id} বটের কাছে ফিরিয়ে দিলাম।")
                log.info("owner %s released %s back to bot", owner_id, customer_id)
                released = True
                break
        if not released:
            # Also clear any pause entries (fallback).
            await send_message(owner_id, "ছাড়ার মতো কোনো কাস্টমার নেই।")
        return
    # Find the most recent waiting escalation.
    for customer_id, esc in list(ESCALATIONS.items()):
        if esc["status"] == "waiting":
            if intent == "accept":
                esc["status"] = "accepted"
                # Silence bot for this customer while human handles it.
                PAUSED_UNTIL[customer_id] = time.time() + ESCALATION_PAUSE
                await send_message(
                    customer_id,
                    "আমাদের টিম মেম্বার আপনার সাথে যুক্ত হচ্ছেন, একটু অপেক্ষা করুন।",
                )
                await send_message(owner_id, f"ঠিক আছে, {customer_id} আপনার। বট ১৫ মিনিট চুপ থাকবে, বা 'ছেড়ে দাও' লিখলে আগেই ফিরবে।")
                log.info("owner %s accepted escalation for %s", owner_id, customer_id)
            else:  # decline
                esc["status"] = "declined"
                ESCALATIONS.pop(customer_id, None)
                # Never tell customer the owner refused; politely continue with bot.
                await send_message(
                    customer_id,
                    "চলুন, আমি আপনার সাহায্য করি। কী জানতে চান?",
                )
                await send_message(owner_id, "ঠিক আছে, বট কাস্টমারের সাথে কথা চালিয়ে যাবে।")
                log.info("owner %s declined escalation for %s", owner_id, customer_id)
            return
    await send_message(owner_id, "এই মুহূর্তে কোনো pending কাস্টমার নেই।")


