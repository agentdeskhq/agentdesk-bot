async def send_message(recipient_id, text):
    url = f"https://graph.facebook.com/{GRAPH_VERSION}/me/messages"
    async with httpx.AsyncClient(timeout=30) as client:
        r = await client.post(url, params={"access_token": PAGE_ACCESS_TOKEN}, json={"recipient": {"id": recipient_id}, "message": {"text": text}})
        r.raise_for_status()
    LAST_BOT_SEND[recipient_id] = time.time()


async def handle_message(sender_id, text, cfg):
    if is_paused(sender_id):
        log.info("bot paused for %s, skipping", sender_id)
        return
    history = get_history(sender_id)
    if needs_escalation(text):
        await notify_admin(sender_id, text)
        add_history(sender_id, "user", text)
        esc_reply = "আপনার মেসেজটি আমাদের টিমের কাছে পাঠিয়ে দিয়েছি, শীঘ্রই কেউ রিপ্লাই দেবে। ধন্যবাদ!"
        add_history(sender_id, "model", esc_reply)
        await send_message(sender_id, esc_reply)
        return
    reply = match_faq(text)
    source = "faq" if reply else None
    if not reply:
        reply = get_similar_cached(text)
        source = "similar-cache" if reply else None
    if not reply:
        try:
            reply = await generate_reply(text, build_system_prompt(cfg, bool(history)), history)
            source = "ai"
        except Exception as e:
            log.warning("all providers failed: %s", e)
            reply = ""
        if reply:
            set_dynamic_cached(text, reply)
    if reply:
        log.info("reply source=%s chars=%d", source, len(reply))
        add_history(sender_id, "user", text)
        add_history(sender_id, "model", reply)
        await send_message(sender_id, reply)
    else:
        await send_message(sender_id, "দুঃখিত, এই মুহূর্তে একটু ব্যস্ত আছি। কিছুক্ষণ পর আবার মেসেজ করুন।")


def verify_signature(body, signature=None):
    if not APP_SECRET:
        return True
    if not signature or not signature.startswith("sha256="):
        return False
    expected = hmac.new(APP_SECRET.encode(), body, hashlib.sha256).hexdigest()
    return hmac.compare_digest("sha256=" + expected, signature)


